import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { validateSchema } from "./lib/json-schema-lite.mjs";
import { projectHubRuntime } from "./lib/classroom-explorations-hub-contract.mjs";
const root = resolve(new URL("..", import.meta.url).pathname);
const readJson = async (path) => JSON.parse(await readFile(resolve(root, path), "utf8"));
const source = await readJson("apps/classroom-explorations-hub/source/hub.source.json");
const routes = await readJson("registry/hrv-routes.source.json");
validateSchema(source, await readJson("schemas/hrv-page-envelope.schema.json"));
validateSchema(source.data, await readJson("schemas/classroom-explorations-hub.source.schema.json"), "$.data");
validateSchema(routes, await readJson("schemas/hrv-route-registry.schema.json"));
const runtime = projectHubRuntime(source, routes);
validateSchema(runtime, await readJson("schemas/classroom-explorations-hub.runtime.schema.json"));
const hash = runtime.snapshotId.slice("sha256:".length);
const out = resolve(root, `dist/classroom-explorations-hub/content/${hash}/manifest.json`);
await rm(resolve(root, "dist/classroom-explorations-hub/content"), { recursive: true, force: true });
await mkdir(dirname(out), { recursive: true });
await writeFile(out, `${JSON.stringify(runtime, null, 2)}\n`, "utf8");
await writeFile(resolve(root, "dist/classroom-explorations-hub/content-snapshot.json"), `${JSON.stringify({ schemaVersion: "1.0", snapshotId: runtime.snapshotId, manifestPath: `content/${hash}/manifest.json`, canonicalSha256: hash }, null, 2)}\n`, "utf8");
console.log(`[hub] content snapshot ${runtime.snapshotId}`);
